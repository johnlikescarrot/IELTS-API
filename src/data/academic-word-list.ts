export const SUBLIST_COUNT = SUBLIST_WORDS.length;

export const AWL_ENTRIES: readonly AwlEntry[] = SUBLIST_WORDS.flatMap((words, index) =>
  words.map((word) => ({ word, sublist: index + 1 }))
);

export const AWL_INDEX: ReadonlyMap<string, AwlEntry> = new Map(
  AWL_ENTRIES.map((entry) => [entry.word, entry])
);

export const AWL_SOURCE = {
  citation: 'Coxhead, A. (2000). A New Academic Word List. TESOL Quarterly, 34(2), 213-238.',
  url: 'https://simple.wiktionary.org/wiki/Wiktionary:Academic_word_list',
  note: 'Word-family headwords; inflected variants appear in the original published list.'
} as const;

export function getSublistWords(sublist: number): readonly string[] {
  return SUBLIST_WORDS[sublist - 1] ?? [];
}

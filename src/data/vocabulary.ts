/** Return vocabulary entries for a given topic. */
export function getVocabularyByTopic(topicId: string): VocabularyEntry[] {
  return vocabulary.filter((entry) => entry.topicId === topicId);
}

/** Find a single vocabulary entry by id. */
export function getVocabularyById(id: string): VocabularyEntry | undefined {
  return vocabulary.find((entry) => entry.id === id);
}

/** Search vocabulary by word, definition, synonyms or example (case-insensitive). */
export function searchVocabulary(query: string): VocabularyEntry[] {
  const q = query.trim().toLowerCase();
  if (q === "") {
    return vocabulary;
  }
  return vocabulary.filter((entry) => {
    const haystack = [entry.word, entry.definition, ...entry.synonyms, entry.example]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}

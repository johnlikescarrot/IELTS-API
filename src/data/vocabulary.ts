/**
 * Search the vocabulary list by a free-text query against the word, definition,
 * example, and category. Matching is case-insensitive and substring-based.
 */
export function searchVocabulary(query: string): readonly VocabularyWord[] {
  const needle = query.trim().toLowerCase();
  if (needle.length === 0) {
    return VOCABULARY;
  }
  return VOCABULARY.filter((entry) => {
    const haystack = [entry.word, entry.definition, entry.example, entry.category]
      .join(' ')
      .toLowerCase();
    return haystack.includes(needle);
  });
}

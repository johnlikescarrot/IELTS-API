/** Look up a collection by id (case-insensitive). */
export function findCollection(id: string): VocabularyCollection | undefined {
  const needle = id.trim().toLowerCase();
  return VOCAB_COLLECTIONS.find((collection) => collection.id === needle);
}

/** All collection identifiers. */
export const COLLECTION_IDS: readonly string[] = VOCAB_COLLECTIONS.map((collection) => collection.id);
